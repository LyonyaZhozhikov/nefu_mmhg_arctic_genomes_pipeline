#!/usr/bin/env python3
"""Drop scoring sections from a genmod rank model (.ini) whose INFO fields the VCF will not have.

genmod score aborts ("All score plugins has to be defined in vcf header") when any plugin's
info_key is missing, e.g. a local frequency DB (Loqusdb), a still-empty cohort AF, or CADD
before it is downloaded. Categories left without plugins are removed too.

Usage: prune_rank_model.py IN.ini OUT.ini SECTION [SECTION ...]
"""
import re
import sys

src, dst, drop = sys.argv[1], sys.argv[2], set(sys.argv[3:])
lines = open(src).read().splitlines()

# 1. split into top-level sections ([name] at column 0)
blocks, name, cur = [], None, []
for line in lines:
    m = re.match(r"^\[([^\[\]]+)\]\s*$", line)
    if m:
        blocks.append((name, cur))
        name, cur = m.group(1), []
    cur.append(line)
blocks.append((name, cur))

missing = drop - {n for n, _ in blocks}
if missing:
    sys.exit(f"sections not found in {src}: {', '.join(sorted(missing))}")
kept = [(n, b) for n, b in blocks if n not in drop]

# 2. categories still used by a plugin
used = set()
for n, b in kept:
    for line in b:
        m = re.match(r"^\s*category\s*=\s*(\S+)", line)
        if m:
            used.add(m.group(1))

# 3. drop unused [[category]] blocks inside [Categories]
out = []
for n, b in kept:
    if n != "Categories":
        out.extend(b)
        continue
    skip = False
    for line in b:
        m = re.match(r"^\s*\[\[([^\]]+)\]\]", line)
        if m:
            skip = m.group(1) not in used
        if not skip:
            out.append(line)

header = f"# Generated by prune_rank_model.py from {src.split('/')[-1]}; dropped: {', '.join(sorted(drop))}"
open(dst, "w").write("\n".join([header] + out) + "\n")
print(f"{dst}: dropped {', '.join(sorted(drop))}; categories kept: {', '.join(sorted(used))}")
